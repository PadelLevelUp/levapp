/**
 * PAD-683 (players.nickname rule 9d, B-631) — the scanner behind the coach display-name guards
 * (web `src/lib/coach-display-name-guard.test.ts`, mobile `src/lib/coach-display-name-guard.test.ts`).
 *
 * A coach view names a student through the coach's display name: `useCoachDisplayName` /
 * `coachDisplayName(...)` (client) or a server `displayName` field. This finds the lines that
 * read a student's REAL name instead — the player-name accessors — so a new view that prints
 * `{inv.playerName}` fails the guard instead of shipping (the PAD-683 invite picker did).
 *
 * Heuristic on purpose: it matches the accessors the audit found (`playerName`, `personName`,
 * `user.name`, the engine's `declinedPlayerName` / `waitingListPlayerName`, and `.name` on the
 * variable names the code uses for a student row). A line that also resolves the display name
 * (`displayName(`, `displayName ??`, `displayName ||`, `coachDisplayName(`, `nameOf(`) passes.
 * Everything else is either fixed or listed, with its reason, in the app's allowlist.
 */

export interface NameHit {
  file: string;
  line: number;
  text: string;
}

const ACCESSOR =
  /\.(?:playerName|personName|declinedPlayerName|waitingListPlayerName)\b|\.user\??\.name\b|\b(?:p|player|s|b|c|cs|student|item|row|req|inv|participant|option|candidate|entry|verdict|duplicate|it)\??\.name\b/;

const RESOLVED = /\b(?:coachDisplayName|nameOf)\s*\(|\bdisplayName\s*(?:\(|\?\?|\|\|)/;

const COMMENT = /^\s*(?:\/\/|\/\*|\*)/;

/** The lines of one source file that print a student's real name without resolving it. */
export function scanCoachNames(file: string, source: string): NameHit[] {
  const hits: NameHit[] = [];
  source.split("\n").forEach((text, i) => {
    if (COMMENT.test(text)) return;
    if (!ACCESSOR.test(text)) return;
    if (RESOLVED.test(text)) return;
    hits.push({ file, line: i + 1, text: text.trim() });
  });
  return hits;
}

export interface CoachNameListEntry {
  /** Path under the app's root (`apps/web/` or `apps/mobile/`). */
  file: string;
  /** Exact number of hits in the file — a ratchet, enforced both ways. */
  max: number;
  /**
   * `allowed`: the real name is right here (an edit form, the user's own account, a student-only
   * screen, a non-student `.name`). `backlog`: a coach view still to convert (PAD-683 part 2).
   */
  kind: "allowed" | "backlog";
  reason: string;
}

/** Hits per file, for the ratchet. */
export function countByFile(hits: NameHit[]): Record<string, number> {
  return hits.reduce<Record<string, number>>((acc, h) => {
    acc[h.file] = (acc[h.file] ?? 0) + 1;
    return acc;
  }, {});
}

/**
 * The list file's source, regenerated by the guard: counts come from the scan; `kind` and `reason`
 * are kept from the current list, and a file seen for the first time is `backlog` / "UNREVIEWED"
 * (which the guard refuses, so a human gives it a reason before it lands).
 */
export function renderCoachNameList(
  constName: string,
  hits: NameHit[],
  current: readonly CoachNameListEntry[]
): string {
  const counts = countByFile(hits);
  const byFile = new Map(current.map((e) => [e.file, e]));
  const rows = Object.keys(counts)
    .sort()
    .map((file) => {
      const prev = byFile.get(file);
      const lines = hits.filter((h) => h.file === file).map((h) => h.line).join(", ");
      const kind = prev?.kind ?? "backlog";
      const reason = prev?.reason ?? `UNREVIEWED (lines ${lines})`;
      return `  { file: ${JSON.stringify(file)}, max: ${counts[file]}, kind: ${JSON.stringify(kind)}, reason: ${JSON.stringify(reason)} },`;
    });
  return `/**
 * PAD-683 (players.nickname rule 9d) — the files where the coach display-name guard
 * (coach-display-name-guard.test.ts) accepts a real-name accessor, with the number of hits.
 *
 * \`allowed\` entries are places where the real name is right; \`backlog\` entries are coach views
 * still to convert. \`max\` is exact and enforced both ways: more -> resolve the new hit through
 * the display name (never raise \`max\` to make a red go away); fewer -> lower it.
 *
 * Counts are regenerated by the guard itself (reasons and kinds are kept):
 *   UPDATE_COACH_NAME_LIST=1 npx vitest run src/lib/coach-display-name-guard.test.ts
 */
import type { CoachNameListEntry } from "@levelup/config/src/coach-name-scan";

export const ${constName}: readonly CoachNameListEntry[] = [
${rows.join("\n")}
] as const;
`;
}
