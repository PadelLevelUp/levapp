describe("no assertion matches on rendered copy", () => {
  const listed = new Set(BACKLOG.map((e) => e.file));

  it("adds no new file", () => {
    const added = Object.keys(countsByFile)
      .filter((f) => !listed.has(f))
      .sort();
    expect(
      added,
      `these files assert on rendered copy and are not in the backlog. Assert on a ` +
        `data-testid instead — do NOT add them to the backlog to make this pass:\n` +
        added.map((f) => `  ${f}: ${countsByFile[f]}`).join("\n"),
    ).toEqual([]);
  });

  it.each(BACKLOG)("$file is at or below its ratchet ($max)", ({ file, max }) => {
    const actual = countsByFile[file] ?? 0;
    if (actual > max) {
      throw new Error(
        `${file}: ${actual} rendered-text assertions, ratchet is ${max}. ` +
          `A new one was added. Assert on a data-testid instead of raising the ratchet.`,
      );
    }
    if (actual < max) {
      throw new Error(
        `${file}: ${actual} rendered-text assertions, ratchet still says ${max}. ` +
          (actual === 0
            ? `Delete this entry from BACKLOG.`
            : `Lower max to ${actual} in BACKLOG — leaving headroom lets new ones back in silently.`),
      );
    }
    expect(actual).toBe(max);
  });
});

